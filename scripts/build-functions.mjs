#!/usr/bin/env node
/**
 * build-functions.mjs
 * Builds the standalone Cloud Functions deploy directory (plan X6, G3).
 *
 *   functions/src (TypeScript) + shared/src  --esbuild-->  functions-dist/lib/index.js
 *
 * Then writes functions-dist/package.json listing ONLY the runtime packages
 * (firebase-functions, firebase-admin) with the versions from
 * functions/package.json, and creates its own package-lock.json. The result
 * never imports ../shared or any workspace path, so Cloud Build can install
 * and run it on its own. firebase.json points functions.source here.
 *
 * Usage: node scripts/build-functions.mjs [--skip-lock]
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "functions-dist");
const RUNTIME_DEPENDENCIES = ["firebase-functions", "firebase-admin"];
const skipLock = process.argv.includes("--skip-lock");

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

const fail = (problem, fix) => {
  console.error(`build:functions failed: ${problem}\nFix: ${fix}`);
  process.exit(1);
};

const runtimeDependencyVersions = () => {
  const functionsPackage = readJson(join(ROOT, "functions", "package.json"));
  const declared = functionsPackage.dependencies ?? {};
  return Object.fromEntries(
    RUNTIME_DEPENDENCIES.map((name) => {
      if (!declared[name]) fail(`${name} is not listed in functions/package.json`, `npm install -w functions ${name}`);
      return [name, declared[name]];
    })
  );
};

const bundle = async () => {
  await build({
    entryPoints: [join(ROOT, "functions", "src", "index.ts")],
    outfile: join(OUT_DIR, "lib", "index.js"),
    bundle: true,
    platform: "node",
    target: "node22",
    format: "cjs",
    sourcemap: true,
    // Runtime packages are installed by Cloud Build from the generated package.json;
    // everything else (zod, @fbla/shared) is bundled in.
    external: RUNTIME_DEPENDENCIES.flatMap((name) => [name, `${name}/*`]),
    logLevel: "warning",
    legalComments: "linked"
  });
};

const writePackageJson = () => {
  const packageJson = {
    name: "functions",
    private: true,
    description: "GENERATED by scripts/build-functions.mjs. Do not edit; edit functions/ instead.",
    main: "lib/index.js",
    engines: { node: "22" },
    dependencies: runtimeDependencyVersions()
  };
  writeFileSync(join(OUT_DIR, "package.json"), `${JSON.stringify(packageJson, null, 2)}\n`);
};

const writeLockfile = () => {
  // One fixed command string (no user input), so running it through the shell is safe on every OS.
  const result = spawnSync("npm install --package-lock-only --omit=dev --ignore-scripts --no-audit --no-fund", {
    cwd: OUT_DIR,
    stdio: "inherit",
    shell: true
  });
  if (result.status !== 0) {
    fail("could not create functions-dist/package-lock.json", "check your network connection, then run npm run build:functions again");
  }
};

const main = async () => {
  const startedAt = Date.now();
  rmSync(join(OUT_DIR, "lib"), { recursive: true, force: true });
  mkdirSync(join(OUT_DIR, "lib"), { recursive: true });
  await bundle();
  writePackageJson();
  if (!skipLock) writeLockfile();
  console.log(`build:functions: wrote functions-dist/ in ${Date.now() - startedAt} ms`);
};

main().catch((error) => fail(error instanceof Error ? error.message : String(error), "read the esbuild error above"));
